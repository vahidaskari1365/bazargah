/** یکسان‌سازی نویسه‌های عربی/فارسی برای تطبیق بهتر کلیدواژه */
function normalizeFa(s: string): string {
  return s
    .toLowerCase()
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/\u200c/g, ' ') // نیم‌فاصله → فاصله
    .replace(/\s+/g, ' ')
}

function offlineVetAnswer(userText: string): string {
  const t = normalizeFa(userText)
  const hit = OFFLINE_KB.find((item) => item.keys.some((k) => t.includes(normalizeFa(k))))
  const body = hit ? hit.answer : OFFLINE_GENERAL
  return `📡 ${body}\n\n—\n*این پاسخ از دانش‌نامه آفلاین بازارگاه است و جایگزین معاینه دامپزشک نیست.*`
}

export async function POST(req: Request) {
  // شناسایی کاربر — اگر دیتابیس در دسترس نبود (مثل Vercel)، بدون سهمیه ادامه می‌دهیم
  let user: Awaited<ReturnType<typeof getUserFromRequest>> = null
  try {
    user = await getUserFromRequest(req)
  } catch {
    user = null
  }
  const noDb = !user

  try {
    const { messages } = await req.json() as { messages: ChatMessage[] }
    if (!messages || !Array.isArray(messages) || messages.length === 0) {
      return Response.json({ error: 'پیام ارسال نشده است' }, { status: 400 })
    }

    // --- محدودیت پیام روزانه بر اساس پلن (فقط وقتی دیتابیس در دسترس است) ---
    let usageToday = 0
    let dailyLimit = 10
    if (!noDb) {
      try {
        const plan = await db.subscriptionPlan.findUnique({ where: { key: user!.planKey } })
        dailyLimit = plan?.dailyAiMessages ?? 10

        const startOfDay = new Date()
        startOfDay.setHours(0, 0, 0, 0)

        usageToday = await db.aIUsage.count({
          where: { userId: user!.id, type: 'VET', createdAt: { gte: startOfDay } },
        })

        if (usageToday >= dailyLimit) {
          return Response.json({
            error: `سهمیه پیام هوش مصنوعی امروز (${dailyLimit} پیام) تمام شد`,
            limitReached: true,
            planName: plan?.name,
            upgradeHint: user!.planKey === 'FREE' ? 'با ارتقای اشتراک، سهمیه پیام‌ها چند برابر می‌شود' : null,
          }, { status: 429 })
        }
      } catch {
        dailyLimit = 10
      }
    }

    // --- Anti-spam: طول پیام ---
    const lastUserMsg = [...messages].reverse().find(m => m.role === 'user')
    if (!lastUserMsg || lastUserMsg.content.trim().length < 2) {
      return Response.json({ error: 'متن پیام کوتاه است' }, { status: 400 })
    }
    if (lastUserMsg.content.length > 3000) {
      return Response.json({ error: 'متن پیام بیش از حد طولانی است (حداکثر 3000 نویسه)' }, { status: 400 })
    }

    // --- فراخوانی هوش مصنوعی واقعی + fallback آفلاین هنگام قطعی سرویس ---
    const aiMessages: ChatMessage[] = [
      { role: 'system', content: VET_SYSTEM_PROMPT },
      // حداکثر 12 پیام آخر برای حفظ زمینه گفتگو با مدیریت توکن
      ...messages.slice(-12),
    ]

    let content: string
    let tokens: number
    let fallback = false
    try {
      const r = await aiChat(aiMessages, 1600, 0.5)
      content = r.content
      tokens = r.tokens
    } catch (aiErr) {
      console.error('AI service unavailable, using offline KB:', aiErr)
      content = offlineVetAnswer(lastUserMsg.content)
      tokens = Math.ceil(content.length / 3)
      fallback = true
    }

    // --- ثبت Usage (در صورت در دسترس بودن دیتابیس) ---
    if (!noDb) {
      await db.aIUsage.create({
        data: { userId: user!.id, type: 'VET', tokens, cost: tokens * 0.00002 },
      }).catch(() => {})
    }

    return Response.json({
      reply: content,
      fallback,
      usage: noDb
        ? { used: 1, limit: 999, remaining: 998 }
        : { used: usageToday + 1, limit: dailyLimit, remaining: Math.max(dailyLimit - usageToday - 1, 0) },
    })
  } catch (e) {
    console.error('AI Vet error:', e)
    return Response.json({ error: 'خطا در پردازش هوش مصنوعی. لطفاً دوباره تلاش کنید.' }, { status: 500 })
  }
}
